import React from 'react';
import { X, Info, Tag } from 'lucide-react';
import type { ClauseAnalysis, RiskLevel } from '../types';

interface ClauseDrawerProps {
  clause: ClauseAnalysis | null;
  onClose: () => void;
}

export const ClauseDrawer: React.FC<ClauseDrawerProps> = ({ clause, onClose }) => {
  if (!clause) return null;

  const getRiskBadgeStyles = (level: RiskLevel) => {
    switch (level) {
      case 'VERY HIGH':
        return 'bg-rose-50 text-rose-700 border-rose-200';
      case 'HIGH':
        return 'bg-red-50 text-red-700 border-red-200';
      case 'MEDIUM':
        return 'bg-amber-50 text-amber-700 border-amber-200';
      case 'MODERATE':
        return 'bg-yellow-50 text-yellow-700 border-yellow-200';
      case 'LOW':
      default:
        return 'bg-emerald-50 text-emerald-700 border-emerald-200';
    }
  };

  return (
    <div className="fixed inset-0 z-50 overflow-hidden">
      {/* Backdrop */}
      <div 
        className="absolute inset-0 bg-slate-900/40 transition-opacity"
        onClick={onClose}
      />

      {/* Drawer Panel */}
      <div className="fixed inset-y-0 right-0 max-w-full flex pl-10">
        <div className="w-screen max-w-lg bg-white border-l border-slate-200 shadow-xl flex flex-col">
          {/* Header */}
          <div className="px-6 py-4 border-b border-slate-100 flex items-center justify-between bg-slate-50">
            <div className="flex items-center space-x-2">
              <span className="text-xs font-mono font-semibold px-2 py-0.5 rounded bg-slate-200 text-slate-800">
                Clause #{clause.clause_no}
              </span>
              <span className="text-sm font-semibold text-slate-900">Clause Details</span>
            </div>
            <button
              onClick={onClose}
              className="p-1 rounded-md text-slate-400 hover:text-slate-600 hover:bg-slate-100"
              aria-label="Close clause details"
            >
              <X className="w-5 h-5" />
            </button>
          </div>

          {/* Scrollable Content */}
          <div className="flex-1 overflow-y-auto p-6 space-y-6">
            {/* Classification & Risk Overview */}
            <div className="p-4 rounded-lg border border-slate-200 bg-white space-y-3">
              <div className="flex items-center justify-between">
                <div>
                  <span className="text-[11px] uppercase tracking-wider text-slate-400 font-semibold block">
                    Predicted Category
                  </span>
                  <h3 className="text-base font-bold text-slate-900 mt-0.5">{clause.category}</h3>
                </div>
                <div className="text-right">
                  <span className="text-[11px] uppercase tracking-wider text-slate-400 font-semibold block">
                    Assigned Risk
                  </span>
                  <div className="flex items-center space-x-1.5 mt-0.5 justify-end">
                    <span className="text-lg font-bold text-slate-900">{clause.risk_score}</span>
                    <span className="text-xs text-slate-400">/ 85</span>
                    <span className={`text-[11px] px-2 py-0.5 rounded-full font-medium border ${getRiskBadgeStyles(clause.risk_level)}`}>
                      {clause.risk_level}
                    </span>
                  </div>
                </div>
              </div>

              {/* Confidence */}
              <div className="pt-2 border-t border-slate-100 flex items-center justify-between text-xs text-slate-600">
                <span>Model Confidence:</span>
                <span className="font-mono font-medium">
                  {clause.confidence_pct !== null ? `${clause.confidence_pct}%` : 'Not available'}
                </span>
              </div>
            </div>

            {/* Plain English Explanation */}
            <div className="space-y-2">
              <div className="flex items-center space-x-2 text-slate-900 font-semibold text-sm">
                <Info className="w-4 h-4 text-slate-500" />
                <span>Plain-English Interpretation</span>
              </div>
              <div className="p-4 rounded-lg bg-slate-50 border border-slate-200 text-sm text-slate-700 leading-relaxed">
                {clause.plain_english}
              </div>
              <p className="text-[11px] text-slate-400 leading-normal italic">
                Note: This explanation describes standard terms within this risk category and is generated by project rules, not customized legal counsel.
              </p>
            </div>

            {/* Original Legal Clause Text */}
            <div className="space-y-2">
              <span className="text-xs font-semibold uppercase tracking-wider text-slate-500 block">
                Original Legal Wording
              </span>
              <div className="p-4 rounded-lg border border-slate-200 bg-white text-sm font-serif leading-relaxed text-slate-900 selection:bg-slate-200">
                "{clause.clause}"
              </div>
            </div>

            {/* Explainability - Important Terms */}
            <div className="space-y-2">
              <div className="flex items-center space-x-2 text-slate-900 font-semibold text-sm">
                <Tag className="w-4 h-4 text-slate-500" />
                <span>Salient TF-IDF N-grams</span>
              </div>
              {clause.important_terms && clause.important_terms.length > 0 ? (
                <div className="flex flex-wrap gap-1.5 pt-1">
                  {clause.important_terms.map((term, idx) => (
                    <span
                      key={idx}
                      className="inline-flex items-center px-2 py-1 rounded bg-slate-100 border border-slate-200 text-xs font-mono text-slate-700"
                    >
                      {term}
                    </span>
                  ))}
                </div>
              ) : (
                <p className="text-xs text-slate-500 italic bg-slate-50 p-3 rounded border border-slate-200">
                  No dominant category-specific n-grams isolated for this clause.
                </p>
              )}
              <p className="text-[11px] text-slate-400 leading-normal">
                These terms contributed most significantly to the model's classification decision based on feature weights.
              </p>
            </div>
          </div>

          {/* Footer */}
          <div className="p-4 border-t border-slate-100 bg-slate-50 text-right">
            <button
              onClick={onClose}
              className="px-4 py-2 bg-slate-900 text-white text-sm font-medium rounded-md hover:bg-slate-800 transition-colors"
            >
              Close
            </button>
          </div>
        </div>
      </div>
    </div>
  );
};
